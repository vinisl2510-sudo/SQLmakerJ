package com.sqlmaker.backend.service;

import com.sqlmaker.backend.dto.ColunaManual;
import com.sqlmaker.backend.dto.GeracaoManualRequest;
import com.sqlmaker.backend.dto.GeracaoManualResponse;
import com.sqlmaker.backend.dto.ReferenciaColuna;
import com.sqlmaker.backend.dto.TabelaManual;
import com.sqlmaker.backend.exception.ModeloManualInvalidoException;
import com.sqlmaker.backend.model.BancoDestino;
import com.sqlmaker.backend.model.TipoColuna;
import com.sqlmaker.backend.service.dialeto.DialetoMysql;
import com.sqlmaker.backend.service.dialeto.DialetoOracle;
import com.sqlmaker.backend.service.dialeto.DialetoPostgresql;
import java.util.List;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

class GeracaoManualServiceTest {

    private final GeracaoManualService service = new GeracaoManualService(
            List.of(new DialetoMysql(), new DialetoPostgresql(), new DialetoOracle()),
            new ValidacaoManualService()
    );

    @Test
    void deveGerarTabelaNoMysql() {
        GeracaoManualResponse resposta = service.gerar(pedido(
                BancoDestino.MYSQL,
                "aluno",
                new TabelaManual("aluno", List.of(
                        id(),
                        coluna("nome", TipoColuna.VARCHAR, 150, true, false),
                        coluna("email", TipoColuna.VARCHAR, 150, false, true),
                        coluna("ativo", TipoColuna.BOOLEAN, null, true, false)
                ))
        ));

        assertEquals("aluno.sql", resposta.arquivos().get(0).nome());
        assertEquals("8.0", resposta.versao());
        assertEquals("""
                -- Gerado pelo SQLmakerJ para MySQL 8.0

                CREATE TABLE aluno (
                    id    INT AUTO_INCREMENT PRIMARY KEY,
                    nome  VARCHAR(150) NOT NULL,
                    email VARCHAR(150) UNIQUE,
                    ativo BOOLEAN NOT NULL
                );
                """, resposta.arquivos().get(0).conteudo());
    }

    @Test
    void deveCriarTabelaReferenciadaAntesNoPostgresql() {
        GeracaoManualResponse resposta = service.gerar(pedido(
                BancoDestino.POSTGRESQL,
                "escola.sql",
                new TabelaManual("aluno", List.of(
                        id(),
                        coluna("nome", TipoColuna.VARCHAR, 100, true, false),
                        chaveEstrangeira("curso_id", "curso")
                )),
                new TabelaManual("curso", List.of(
                        id(),
                        decimal("preco", 10, 2, true),
                        coluna("criado_em", TipoColuna.DATETIME, null, true, false)
                ))
        ));

        assertEquals("escola.sql", resposta.arquivos().get(0).nome());
        assertEquals("""
                -- Gerado pelo SQLmakerJ para PostgreSQL 16

                CREATE TABLE curso (
                    id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    preco     NUMERIC(10,2) NOT NULL,
                    criado_em TIMESTAMP NOT NULL
                );

                CREATE TABLE aluno (
                    id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    nome     VARCHAR(100) NOT NULL,
                    curso_id INTEGER NOT NULL,
                    FOREIGN KEY (curso_id) REFERENCES curso (id)
                );
                """, resposta.arquivos().get(0).conteudo());
        assertTrue(resposta.explicacao().contains("nesta ordem: curso e aluno"));
    }

    @Test
    void deveTraduzirTiposParaOracle() {
        GeracaoManualResponse resposta = service.gerar(pedido(
                BancoDestino.ORACLE,
                "produto",
                new TabelaManual("produto", List.of(
                        id(),
                        coluna("nome", TipoColuna.VARCHAR, 100, true, false),
                        coluna("sigla", TipoColuna.CHAR, 2, false, false),
                        coluna("descricao", TipoColuna.TEXT, null, false, false),
                        coluna("ativo", TipoColuna.BOOLEAN, null, true, false)
                ))
        ));

        assertEquals("""
                -- Gerado pelo SQLmakerJ para Oracle 19c

                CREATE TABLE produto (
                    id        NUMBER(10,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    nome      VARCHAR2(100 CHAR) NOT NULL,
                    sigla     CHAR(2 CHAR),
                    descricao CLOB,
                    ativo     NUMBER(1,0) NOT NULL CHECK (ativo IN (0, 1))
                );
                """, resposta.arquivos().get(0).conteudo());
    }

    @Test
    void deveUsarChavePrimariaCompostaNoFimDaTabela() {
        GeracaoManualResponse resposta = service.gerar(pedido(
                BancoDestino.MYSQL,
                "matricula",
                new TabelaManual("aluno", List.of(id())),
                new TabelaManual("curso", List.of(id())),
                new TabelaManual("matricula", List.of(
                        new ColunaManual("aluno_id", TipoColuna.INT, null, null,
                                true, false, true, false,
                                new ReferenciaColuna("aluno", "id")),
                        new ColunaManual("curso_id", TipoColuna.INT, null, null,
                                true, false, true, false,
                                new ReferenciaColuna("curso", "id"))
                ))
        ));

        assertTrue(resposta.arquivos().get(0).conteudo().contains("""
                CREATE TABLE matricula (
                    aluno_id INT,
                    curso_id INT,
                    PRIMARY KEY (aluno_id, curso_id),
                    FOREIGN KEY (aluno_id) REFERENCES aluno (id),
                    FOREIGN KEY (curso_id) REFERENCES curso (id)
                );
                """));
    }

    @Test
    void deveAdiarChaveEstrangeiraEmReferenciaCircular() {
        GeracaoManualResponse resposta = service.gerar(pedido(
                BancoDestino.ORACLE,
                "circular",
                new TabelaManual("departamento", List.of(
                        id(),
                        chaveEstrangeira("chefe_id", "funcionario")
                )),
                new TabelaManual("funcionario", List.of(
                        id(),
                        chaveEstrangeira("departamento_id", "departamento"),
                        chaveEstrangeira("gerente_id", "funcionario")
                ))
        ));

        String sql = resposta.arquivos().get(0).conteudo();

        assertTrue(sql.contains("    FOREIGN KEY (departamento_id) REFERENCES departamento (id),\n"
                + "    FOREIGN KEY (gerente_id) REFERENCES funcionario (id)\n"));
        assertTrue(sql.endsWith("""

                ALTER TABLE departamento ADD FOREIGN KEY (chefe_id) REFERENCES funcionario (id);
                """));
        assertTrue(resposta.explicacao().contains("ALTER TABLE"));
    }

    @Test
    void deveJuntarTodosOsProblemasDaEstrutura() {
        ModeloManualInvalidoException erro = assertThrows(
                ModeloManualInvalidoException.class,
                () -> service.gerar(pedido(
                        BancoDestino.MYSQL,
                        "erros",
                        new TabelaManual("pedido", List.of(
                                coluna("order", TipoColuna.INT, null, false, false),
                                coluna("descricao", TipoColuna.VARCHAR, null, false, false),
                                coluna("descricao", TipoColuna.TEXT, null, false, true),
                                chaveEstrangeira("cliente_id", "cliente")
                        ))
                ))
        );

        assertEquals(List.of(
                "Tabela \"pedido\", coluna \"order\": ORDER é uma palavra reservada no MySQL. Escolha outro nome.",
                "Tabela \"pedido\", coluna \"descricao\": informe o tamanho.",
                "Tabela \"pedido\", coluna \"descricao\": no MySQL, TEXT não pode ser PK nem Única. Escolha um texto com tamanho.",
                "Tabela \"pedido\": há mais de uma coluna chamada \"descricao\".",
                "Tabela \"pedido\": marque pelo menos uma coluna como PK.",
                "Tabela \"pedido\", coluna \"cliente_id\": a tabela \"cliente\" não está entre as tabelas do arquivo."
        ), erro.getErros());
    }

    @Test
    void deveRespeitarLimitesDeCadaBanco() {
        TabelaManual tabela = new TabelaManual("cliente", List.of(
                id(),
                coluna("observacao", TipoColuna.VARCHAR, 5000, false, false)
        ));

        ModeloManualInvalidoException erro = assertThrows(
                ModeloManualInvalidoException.class,
                () -> service.gerar(pedido(BancoDestino.ORACLE, "cliente", tabela))
        );

        assertEquals(
                "Tabela \"cliente\", coluna \"observacao\": no Oracle, o tamanho vai de 1 a 4.000.",
                erro.getMessage()
        );

        GeracaoManualResponse postgresql =
                service.gerar(pedido(BancoDestino.POSTGRESQL, "cliente", tabela));

        assertTrue(postgresql.arquivos().get(0).conteudo().contains("VARCHAR(5000)"));
    }

    @Test
    void deveExigirMesmoTipoNaChaveEstrangeira() {
        ModeloManualInvalidoException erro = assertThrows(
                ModeloManualInvalidoException.class,
                () -> service.gerar(pedido(
                        BancoDestino.ORACLE,
                        "loja",
                        new TabelaManual("cliente", List.of(id())),
                        new TabelaManual("compra", List.of(
                                id(),
                                new ColunaManual("cliente_id", TipoColuna.BIGINT, null, null,
                                        false, false, true, false,
                                        new ReferenciaColuna("CLIENTE", "ID"))
                        ))
                ))
        );

        assertEquals(
                "Tabela \"compra\", coluna \"cliente_id\": o tipo precisa ser igual ao de \"cliente.id\" (NUMBER(10,0)).",
                erro.getMessage()
        );
    }

    @Test
    void deveExigirColunaAutomaticaInteiraEUnica() {
        ModeloManualInvalidoException erro = assertThrows(
                ModeloManualInvalidoException.class,
                () -> service.gerar(pedido(
                        BancoDestino.POSTGRESQL,
                        "nota",
                        new TabelaManual("nota", List.of(
                                id(),
                                new ColunaManual("numero", TipoColuna.INT, null, null,
                                        false, true, true, false, null),
                                new ColunaManual("codigo", TipoColuna.VARCHAR, 10, null,
                                        false, true, true, true, null)
                        ))
                ))
        );

        assertEquals(List.of(
                "Tabela \"nota\": só uma coluna pode ser automática.",
                "Tabela \"nota\", coluna \"numero\": uma coluna automática precisa ser a única PK da tabela ou estar marcada como Única.",
                "Tabela \"nota\", coluna \"codigo\": só colunas de número inteiro (INT ou BIGINT) podem ser automáticas."
        ), erro.getErros());
    }

    private GeracaoManualRequest pedido(
            BancoDestino banco,
            String nomeArquivo,
            TabelaManual... tabelas
    ) {
        return new GeracaoManualRequest(banco, nomeArquivo, List.of(tabelas));
    }

    private ColunaManual id() {
        return new ColunaManual("id", TipoColuna.INT, null, null,
                true, true, true, false, null);
    }

    private ColunaManual coluna(
            String nome,
            TipoColuna tipo,
            Integer tamanho,
            boolean obrigatorio,
            boolean unico
    ) {
        return new ColunaManual(nome, tipo, tamanho, null,
                false, false, obrigatorio, unico, null);
    }

    private ColunaManual decimal(
            String nome,
            int tamanho,
            int escala,
            boolean obrigatorio
    ) {
        return new ColunaManual(nome, TipoColuna.DECIMAL, tamanho, escala,
                false, false, obrigatorio, false, null);
    }

    private ColunaManual chaveEstrangeira(String nome, String tabela) {
        return new ColunaManual(nome, TipoColuna.INT, null, null,
                false, false, true, false,
                new ReferenciaColuna(tabela, "id"));
    }
}
