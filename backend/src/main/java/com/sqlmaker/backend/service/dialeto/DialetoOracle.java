package com.sqlmaker.backend.service.dialeto;

import com.sqlmaker.backend.dto.ColunaManual;
import com.sqlmaker.backend.model.BancoDestino;
import com.sqlmaker.backend.model.TipoColuna;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Optional;
import java.util.Set;
import org.springframework.stereotype.Component;

@Component
public class DialetoOracle implements DialetoSql {

    // Palavras reservadas do SQL do Oracle (SQL Language Reference).
    private static final Set<String> RESERVADAS = DialetoSql.palavras("""
            ACCESS ADD ALL ALTER AND ANY AS ASC AUDIT BETWEEN BY CHAR CHECK CLUSTER
            COLUMN COLUMN_VALUE COMMENT COMPRESS CONNECT CREATE CURRENT DATE DECIMAL
            DEFAULT DELETE DESC DISTINCT DROP ELSE EXCLUSIVE EXISTS FILE FLOAT FOR
            FROM GRANT GROUP HAVING IDENTIFIED IMMEDIATE IN INCREMENT INDEX INITIAL
            INSERT INTEGER INTERSECT INTO IS LEVEL LIKE LOCK LONG MAXEXTENTS MINUS
            MLSLABEL MODE MODIFY NESTED_TABLE_ID NOAUDIT NOCOMPRESS NOT NOWAIT NULL
            NUMBER OF OFFLINE ON ONLINE OPTION OR ORDER PCTFREE PRIOR PUBLIC RAW
            RENAME RESOURCE REVOKE ROW ROWID ROWNUM ROWS SELECT SESSION SET SHARE
            SIZE SMALLINT START SUCCESSFUL SYNONYM SYSDATE TABLE THEN TO TRIGGER UID
            UNION UNIQUE UPDATE USER VALIDATE VALUES VARCHAR VARCHAR2 VIEW WHENEVER
            WHERE WITH
            """);

    @Override
    public BancoDestino banco() {
        return BancoDestino.ORACLE;
    }

    @Override
    public String nome() {
        return "Oracle";
    }

    @Override
    public String versao() {
        return "19c";
    }

    @Override
    public String tipo(ColunaManual coluna) {
        return switch (coluna.tipo()) {
            case INT -> "NUMBER(10,0)";
            case BIGINT -> "NUMBER(19,0)";
            // Tamanho em caracteres, e não em bytes, para letras acentuadas não contarem dobrado.
            case VARCHAR -> "VARCHAR2(" + coluna.tamanho() + " CHAR)";
            case CHAR -> "CHAR(" + coluna.tamanho() + " CHAR)";
            case TEXT -> "CLOB";
            case DECIMAL -> "NUMBER(" + coluna.tamanho() + "," + coluna.escala() + ")";
            case BOOLEAN -> "NUMBER(1,0)";
            case DATE -> "DATE";
            case DATETIME -> "TIMESTAMP";
        };
    }

    @Override
    public String autoIncremento() {
        return "GENERATED BY DEFAULT AS IDENTITY";
    }

    @Override
    public int tamanhoMaximo(TipoColuna tipo) {
        return switch (tipo) {
            case VARCHAR -> 4000;
            case CHAR -> 2000;
            case DECIMAL -> 38;
            default -> 0;
        };
    }

    @Override
    public int escalaMaxima() {
        return 38;
    }

    @Override
    public boolean textoLongoAceitaChave() {
        return false;
    }

    @Override
    public boolean palavraReservada(String nome) {
        return RESERVADAS.contains(nome.toUpperCase(Locale.ROOT));
    }

    // O Oracle 19c não tem BOOLEAN em tabelas: o CHECK limita a coluna a 0 e 1.
    @Override
    public Optional<String> checagem(ColunaManual coluna) {
        if (coluna.tipo() != TipoColuna.BOOLEAN) {
            return Optional.empty();
        }

        return Optional.of("CHECK (" + coluna.nome() + " IN (0, 1))");
    }

    @Override
    public List<String> observacoes(Set<TipoColuna> tiposUsados) {
        List<String> observacoes = new ArrayList<>();

        if (tiposUsados.contains(TipoColuna.VARCHAR)
                || tiposUsados.contains(TipoColuna.CHAR)) {
            observacoes.add(
                    "No Oracle, VARCHAR vira VARCHAR2, e o tamanho dos textos é contado em caracteres (CHAR), não em bytes."
            );
        }

        if (tiposUsados.contains(TipoColuna.INT)
                || tiposUsados.contains(TipoColuna.BIGINT)) {
            observacoes.add(
                    "Os inteiros usam NUMBER sem casas decimais: NUMBER(10,0) no lugar de INT e NUMBER(19,0) no lugar de BIGINT."
            );
        }

        if (tiposUsados.contains(TipoColuna.TEXT)) {
            observacoes.add("TEXT vira CLOB.");
        }

        if (tiposUsados.contains(TipoColuna.BOOLEAN)) {
            observacoes.add(
                    "O Oracle 19c não tem BOOLEAN em tabelas, então as colunas booleanas usam NUMBER(1,0) com um CHECK que aceita só 0 e 1."
            );
        }

        if (tiposUsados.contains(TipoColuna.DATE)) {
            observacoes.add("No Oracle, DATE também guarda a hora.");
        }

        return observacoes;
    }
}
