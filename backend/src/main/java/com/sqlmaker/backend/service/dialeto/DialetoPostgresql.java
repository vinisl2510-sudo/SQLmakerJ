package com.sqlmaker.backend.service.dialeto;

import com.sqlmaker.backend.dto.ColunaManual;
import com.sqlmaker.backend.model.BancoDestino;
import com.sqlmaker.backend.model.TipoColuna;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import org.springframework.stereotype.Component;

@Component
public class DialetoPostgresql implements DialetoSql {

    // Palavras "reserved" e "reserved (can be function or type)" do PostgreSQL:
    // nenhuma delas pode ser nome de tabela ou de coluna sem aspas.
    private static final Set<String> RESERVADAS = DialetoSql.palavras("""
            ALL ANALYSE ANALYZE AND ANY ARRAY AS ASC ASYMMETRIC AUTHORIZATION BINARY
            BOTH CASE CAST CHECK COLLATE COLLATION COLUMN CONCURRENTLY CONSTRAINT
            CREATE CROSS CURRENT_CATALOG CURRENT_DATE CURRENT_ROLE CURRENT_SCHEMA
            CURRENT_TIME CURRENT_TIMESTAMP CURRENT_USER DEFAULT DEFERRABLE DESC
            DISTINCT DO ELSE END EXCEPT FALSE FETCH FOR FOREIGN FREEZE FROM FULL
            GRANT GROUP HAVING ILIKE IN INITIALLY INNER INTERSECT INTO IS ISNULL
            JOIN LATERAL LEADING LEFT LIKE LIMIT LOCALTIME LOCALTIMESTAMP NATURAL NOT
            NOTNULL NULL OFFSET ON ONLY OR ORDER OUTER OVERLAPS PLACING PRIMARY
            REFERENCES RETURNING RIGHT SELECT SESSION_USER SIMILAR SOME SYMMETRIC
            SYSTEM_USER TABLE TABLESAMPLE THEN TO TRAILING TRUE UNION UNIQUE USER
            USING VARIADIC VERBOSE WHEN WHERE WINDOW WITH
            """);

    @Override
    public BancoDestino banco() {
        return BancoDestino.POSTGRESQL;
    }

    @Override
    public String nome() {
        return "PostgreSQL";
    }

    @Override
    public String versao() {
        return "16";
    }

    @Override
    public String tipo(ColunaManual coluna) {
        return switch (coluna.tipo()) {
            case INT -> "INTEGER";
            case BIGINT -> "BIGINT";
            case VARCHAR -> "VARCHAR(" + coluna.tamanho() + ")";
            case CHAR -> "CHAR(" + coluna.tamanho() + ")";
            case TEXT -> "TEXT";
            case DECIMAL -> "NUMERIC(" + coluna.tamanho() + "," + coluna.escala() + ")";
            case BOOLEAN -> "BOOLEAN";
            case DATE -> "DATE";
            case DATETIME -> "TIMESTAMP";
        };
    }

    @Override
    public String autoIncremento() {
        return "GENERATED BY DEFAULT AS IDENTITY";
    }

    @Override
    public int tamanhoMaximo(TipoColuna tipo) {
        return switch (tipo) {
            case VARCHAR, CHAR -> 10_485_760;
            case DECIMAL -> 1000;
            default -> 0;
        };
    }

    @Override
    public int escalaMaxima() {
        return 1000;
    }

    @Override
    public boolean textoLongoAceitaChave() {
        return true;
    }

    @Override
    public boolean palavraReservada(String nome) {
        return RESERVADAS.contains(nome.toUpperCase(Locale.ROOT));
    }

    @Override
    public List<String> observacoes(Set<TipoColuna> tiposUsados) {
        List<String> observacoes = new ArrayList<>();

        if (tiposUsados.contains(TipoColuna.DATETIME)) {
            observacoes.add("TIMESTAMP guarda data e hora sem fuso horário.");
        }

        return observacoes;
    }
}
